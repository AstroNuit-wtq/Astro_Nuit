import Foundation

enum CelestialDescriptions {
    
    static func description(for name: String) -> (title: String, subtitle: String, text: String) {
        switch name.lowercased() {
        // Planets
        case "солнце", "sun":
            return ("Солнце",
                    "Звезда спектрального класса G2V",
                    "Центральная звезда Солнечной системы. Диаметр около 1,39 млн км. Температура поверхности ≈ 5500 °C. Состоит в основном из водорода (≈73%) и гелия (≈25%). Источник энергии — термоядерный синтез в ядре.")
            
        case "луна", "moon":
            return ("Луна",
                    "Естественный спутник Земли",
                    "Среднее расстояние до Земли — 384 400 км. Диаметр 3474 км. Покрыта реголитом, имеет моря (базальтовые равнины) и кратеры. Вращается синхронно с Землёй — мы всегда видим одну сторону.")
            
        case "меркурий", "mercury":
            return ("Меркурий",
                    "Ближайшая к Солнцу планета",
                    "Самая маленькая планета Солнечной системы. Год длится 88 земных суток. Поверхность сильно кратерирована, атмосфера практически отсутствует. Большие перепады температуры: от −180 °C до +430 °C.")
            
        case "венера", "venus":
            return ("Венера",
                    "Вторая планета от Солнца",
                    "Самая горячая планета (≈ 465 °C) из-за парникового эффекта. Плотная атмосфера из углекислого газа. Вращается в обратную сторону. Часто называют «сестрой Земли» из-за похожего размера.")
            
        case "марс", "mars":
            return ("Марс",
                    "Красная планета",
                    "Четвёртая планета. Имеет полярные шапки из водяного льда и сухого льда. Крупнейший вулкан Солнечной системы — Олимп. Сутки почти как земные (24 ч 37 мин). Активно исследуется роверами.")
            
        case "юпитер", "jupiter":
            return ("Юпитер",
                    "Крупнейшая планета",
                    "Газовый гигант. Масса больше, чем у всех остальных планет вместе взятых. Великое Красное Пятно — гигантский шторм, существующий сотни лет. Имеет более 90 спутников, включая Ио, Европу, Ганимед и Каллисто.")
            
        case "сатурн", "saturn":
            return ("Сатурн",
                    "Планета с кольцами",
                    "Газовый гигант, известный системой колец из льда и камня. Плотность меньше плотности воды. Имеет крупный спутник Титан с плотной атмосферой и жидкими озёрами из метана.")
            
        case "уран", "uranus":
            return ("Уран",
                    "Ледяной гигант",
                    "Седьмая планета. Вращается «на боку» — ось наклонена почти на 98°. Имеет слабую систему колец. Атмосфера содержит метан, из-за которого планета имеет голубоватый цвет.")
            
        case "нептун", "neptune":
            return ("Нептун",
                    "Самая дальняя планета",
                    "Восьмая планета. Самые сильные ветры в Солнечной системе (до 2000 км/ч). Открыт по математическим расчётам до визуального наблюдения. Крупный спутник — Тритон.")
            
        // Stars
        case "sirius":
            return ("Сириус (α Большого Пса)",
                    "Ярчайшая звезда ночного неба",
                    "Видимая звёздная величина −1,46. Расстояние ≈ 8,6 световых лет. Двойная система: Сириус A (белая звезда главной последовательности) и Сириус B (белый карлик).")
            
        case "vega":
            return ("Вега (α Лиры)",
                    "Одна из ярчайших звёзд северного неба",
                    "Видимая величина 0,03. Расстояние ≈ 25 световых лет. Была полярной звездой около 12 000 лет назад и снова станет ею. Спектральный класс A0V.")
            
        case "betelgeuse":
            return ("Бетельгейзе (α Ориона)",
                    "Красный сверхгигант",
                    "Одна из крупнейших известных звёзд. Находится на поздней стадии эволюции и в будущем вспыхнет как сверхновая. Расстояние примерно 500–600 световых лет.")
            
        case "rigel":
            return ("Ригель (β Ориона)",
                    "Голубой сверхгигант",
                    "Одна из самых мощных звёзд в ближайших окрестностях Солнца. Светимость в десятки тысяч раз больше солнечной. Спектральный класс B8.")
            
        case "polaris":
            return ("Полярная звезда (α Малой Медведицы)",
                    "Северная полярная звезда",
                    "Находится почти точно на продолжении оси вращения Земли. На самом деле это тройная звёздная система. Используется для навигации уже много веков.")
            
        case "antares":
            return ("Антарес (α Скорпиона)",
                    "Красный сверхгигант",
                    "Название означает «соперник Марса» из-за красноватого цвета. Одна из крупнейших звёзд, видимых невооружённым глазом. Расстояние ≈ 550 световых лет.")
            
        default:
            return (name,
                    "Небесный объект",
                    "Подробное описание будет добавлено в следующих обновлениях.")
        }
    }
}
